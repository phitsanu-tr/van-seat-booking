const HLP=require('../helpers');const {chromium}=require(HLP.PW);const B=HLP.BASE;const errs=[];const log=(...a)=>console.log(...a);
// Booking queue: only the approved person whose turn it is can book; finishing (or booking up to the limit) calls the next one.
(async()=>{const b=await chromium.launch(HLP.launchOpts);
const mk=async(name)=>{const c=await b.newContext({viewport:{width:390,height:800},deviceScaleFactor:1});await HLP.fonts(c);const p=await c.newPage();p.on('pageerror',e=>errs.push(e.message));await p.goto(B+'/api/auth?start=1&as='+name+Date.now()+'&r=%2Fprivacy');await p.waitForTimeout(300);return p};
const post=async(p,path,data)=>{const r=await p.request.post(B+path,{data});return {s:r.status(),j:await r.json().catch(()=>({}))}};
const O=await mk('Org'),A=await mk('Ann'),C=await mk('Bob');
const tr=await (await O.request.post(B+'/api/trip',{data:{name:'ทริปคิว',startDate:HLP.day(20),endDate:HLP.day(21),departTime:'07:00',returnTime:'17:00',tripN:2,tripStart:HLP.day(20),meetPoint:'BTS หมอชิต',vans:[{label:'1'}],maxPerPerson:1}})).json();const t=tr.id;
const q=(p,a,x)=>post(p,'/api/queue',Object.assign({t,a},x||{}));
const book=(p,seat,name)=>post(p,'/api/seats',{t,seat,name});
let r=await q(O,'add',{names:['แอนน์','บ๊อบ']});log('add rows',r.s,r.j.items&&r.j.items.length);
r=await q(A,'add',{names:['แทรก']});log('passenger cannot add',r.s,r.j.error);
await q(O,'on',{value:true});
let g=await (await O.request.get(B+'/api/queue?t='+t)).json();const [ra,rb]=g.items;log('on',g.on,'turn none yet',g.turn===null);
log('seats says queue on',(await (await A.request.get(B+'/api/seats?t='+t)).json()).qon);
r=await q(A,'claim',{id:ra.id});log('A claims',r.s,'mine',!!r.j.mine);
r=await q(C,'claim',{id:ra.id});log('B cannot take A row',r.s,r.j.error);
r=await q(C,'claim',{id:rb.id});log('B claims own',r.s);
r=await book(A,2,'แอนน์');log('A before approval blocked',r.s,r.j.error);
r=await q(O,'ok',{id:ra.id,value:true});log('approved A: turn is A',r.j.turn===ra.id);
r=await book(C,3,'บ๊อบ');log('B not his turn',r.s,r.j.error);
r=await post(C,'/api/seats',{t,hold:3});log('B hold blocked',r.s,r.j.error);
r=await book(A,2,'แอนน์');log('A books',r.s);
g=await (await O.request.get(B+'/api/queue?t='+t)).json();log('limit reached: A done',!!g.items[0].done,'turn none until B approved',g.turn===null);
r=await q(O,'ok',{id:rb.id,value:true});log('approved B: turn is B',r.j.turn===rb.id);
r=await book(A,4,'แอนน์');log('A again blocked',r.s,r.j.error);
r=await book(C,3,'บ๊อบ');log('B books',r.s);
r=await book(O,5,'ผู้จัดจอง');log('organizer always may',r.s);
await q(O,'on',{value:false});r=await book(A,6,'แอนน์');log('queue off: seat_limit not queue error',r.j.error!=='not_your_turn');
await q(O,'on',{value:true});
await A.goto(B+'/'+t+'/queue');await A.waitForTimeout(1500);
log('passenger page shows list',(await A.locator('.row').count()),'rows');
await O.goto(B+'/'+t+'/queue');await O.waitForTimeout(1500);await O.click('.stripw .sx');await O.waitForTimeout(300);
await O.setViewportSize({width:390,height:800});await O.waitForTimeout(200);await O.screenshot({path:HLP.OUT+'/26-org.png'});await A.screenshot({path:HLP.OUT+'/26-pax.png'});
log('organizer page has controls',(await O.locator('.dots').count())>0);
await C.goto(B+'/'+t+'/seats');await C.waitForTimeout(1800);
log('booking page shows queue bar',await C.evaluate(()=>!document.getElementById('queueBar').hidden));
await O.goto(B+'/trips?f='+Date.now());await O.waitForTimeout(1500);await O.click('.mgo');await O.waitForTimeout(400);
log('manage sheet has the queue entry',await O.evaluate(t=>{const a=[...document.querySelectorAll('.sheet a.acti')].find(x=>x.textContent.includes('คิวจองตามลำดับ'));return a?a.getAttribute('href')===('/'+t+'/queue'):false},t));
await O.screenshot({path:HLP.OUT+'/26-manage.png'});
log('ERR',errs);await b.close()})().catch(e=>{console.log('ERR',e.message);process.exit(1)});
